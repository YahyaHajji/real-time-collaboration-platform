CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_user_role CHECK (role IN ('ADMIN', 'MANAGER', 'USER'))
);

CREATE TABLE notification (
    id UUID PRIMARY KEY,
    recipient_user_id BIGINT NOT NULL REFERENCES app_user(id),
    type VARCHAR(80) NOT NULL,
    payload JSONB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE NULL
);
CREATE INDEX idx_notification_recipient_created
    ON notification(recipient_user_id, created_at, id);

CREATE TABLE chat_channel (
    id UUID PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    required_role VARCHAR(20) NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_channel_role CHECK (required_role IS NULL OR required_role IN ('ADMIN', 'MANAGER', 'USER'))
);

CREATE TABLE chat_message (
    id UUID PRIMARY KEY,
    client_message_id UUID NOT NULL,
    channel_id UUID NOT NULL REFERENCES chat_channel(id),
    sender_user_id BIGINT NOT NULL REFERENCES app_user(id),
    body VARCHAR(2000) NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_chat_sender_client UNIQUE (sender_user_id, client_message_id)
);
CREATE INDEX idx_chat_message_channel_sent ON chat_message(channel_id, sent_at, id);

CREATE TABLE chat_read_state (
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    channel_id UUID NOT NULL REFERENCES chat_channel(id),
    last_read_message_id UUID NULL REFERENCES chat_message(id),
    read_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, channel_id)
);

